export type DifficultyLevel = 'EASY' | 'MEDIUM' | 'HARD';
export type LearningLevel = 1 | 2 | 3 | 4;
export type Handedness = 'ONE_HANDED' | 'TWO_HANDED' | 'EITHER';

export interface SignInstruction {
  handConfiguration: string;
  palmOrientation: string;
  movement: string;
  startingPosition: string;
  endingPosition: string;
}

export interface SignDefinition {
  id: string; // e.g. "HELLO"
  signId?: string; // Canonical identifier, e.g. "isl_hello", "isl_a"
  canonicalName: string;
  gloss?: string;
  displayName: string;
  englishMeaning: string;
  category: string;
  subcategory: string;
  difficulty: DifficultyLevel;
  learningLevel: LearningLevel;
  handedness: Handedness;
  instruction: SignInstruction;
  hasVerifiedInstruction: boolean;
  commonMistakes: string;
  practiceTips: string;
  exampleUsage: string;
  exampleSentence?: string;
  image?: string;
  video?: string;
  datasetSources?: string[];
  aiSupported?: boolean;
  staticOrDynamic?: 'STATIC' | 'DYNAMIC';
  verified?: boolean;
  emergency: boolean;
  isAvailableForRecognition: boolean; // True only for validated ML classifier classes
  isAvailableForAssessment: boolean;
  recognitionClass: string | null;
  aliases: string[];
  relatedSigns: string[];
}

