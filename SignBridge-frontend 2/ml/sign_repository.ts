export class SignRepository {
  private static signsMap: Map<string, SignDefinition> = new Map();
  private static categoriesMap: Map<string, SignCategoryMeta> = new Map();

  static {
    RAW_SIGNS_DATABASE.forEach(s => {
      const canonicalSignId = s.signId || ('isl_' + s.id.toLowerCase().replace(/[^a-z0-9_]/g, '_'));
      const firstLetter = s.id.charAt(0).toUpperCase();
      const videoLink = s.video || (s.category === 'NUMBERS' ? 'https://drive.google.com/drive/folders/1QBiSSz2zyV0CvaPRZo4V2jkn8FI2-jsT?usp=drive_link' : ('https://drive.google.com/drive/folders/1nkI7lddegUWDvmGsmn68QkB5ikp5_3kt?usp=drive_link'.includes(firstLetter) ? ('https://drive.google.com/drive/folders/' + firstLetter) : 'https://drive.google.com/drive/folders/1U-Pr4r1-cupgNOOq9NH_uTsQnPSVEKco'));
      const imagePath = s.image || (/^[A-Z]$/.test(s.id) ? `/signs/alphabets/${s.id.toLowerCase()}.jpg` : '');
      const normalizedSign: SignDefinition = {
        ...s,
        signId: canonicalSignId,
        gloss: s.gloss || s.canonicalName || s.id,
        aiSupported: s.aiSupported !== undefined ? s.aiSupported : s.isAvailableForRecognition,
        staticOrDynamic: s.staticOrDynamic || (['COME', 'GO', 'GOOD_MORNING', 'THANK_YOU', 'J', 'Z'].includes(s.id) ? 'DYNAMIC' : 'STATIC'),
        verified: s.verified !== undefined ? s.verified : s.hasVerifiedInstruction,
        exampleSentence: s.exampleSentence || s.exampleUsage,
        image: imagePath,
        video: s.video || videoLink,
        datasetSources: s.datasetSources || ['ISL_CSLTR_Kaggle', 'ISL_Dictionary_Words']
      };

      // Index by canonical signId (e.g. isl_hello, isl_a), uppercase ID (HELLO, A), and canonicalName
      if (normalizedSign.signId) {
        this.signsMap.set(normalizedSign.signId.toLowerCase(), normalizedSign);
      }
      this.signsMap.set(normalizedSign.id.toUpperCase(), normalizedSign);
      this.signsMap.set(normalizedSign.canonicalName.toUpperCase(), normalizedSign);
      normalizedSign.aliases?.forEach(a => {
        if (!this.signsMap.has(a.toLowerCase())) this.signsMap.set(a.toLowerCase(), normalizedSign);
      });
    });

    SIGN_CATEGORIES.forEach(c => {
      this.categoriesMap.set(c.id.toUpperCase(), c);
    });
  }

  public static getAllSigns(): SignDefinition[] {
    // Return unique signs deduplicated by signId or id
    const unique = new Map<string, SignDefinition>();
    for (const s of this.signsMap.values()) {
      const key = s.signId || s.id;
      if (!unique.has(key)) unique.set(key, s);
    }
    return Array.from(unique.values());
  }

  public static getSignById(id: string): SignDefinition | undefined {
    if (!id) return undefined;
    const clean = id.trim();
    return this.signsMap.get(clean) || this.signsMap.get(clean.toLowerCase()) || this.signsMap.get(clean.toUpperCase());
  }

  public static getCategories(): SignCategoryMeta[] {
    return Array.from(this.categoriesMap.values()).sort((a, b) => a.displayOrder - b.displayOrder);
  }

  public static getCategoryById(id: string): SignCategoryMeta | undefined {
    if (!id) return undefined;
    return this.categoriesMap.get(id.toUpperCase().trim());
  }

  public static getCameraSupportedSigns(): SignDefinition[] {
    return this.getAllSigns().filter(s => s.aiSupported || s.isAvailableForRecognition);
  }

  public static getCameraSupportedCount(): number {
    return this.getCameraSupportedSigns().length;
  }

  public static getTotalCount(): number {
    return this.getAllSigns().length;
  }

  public static searchSigns(params?: {
    query?: string;
    category?: string;
    difficulty?: string;
    learningLevel?: number;
    handedness?: string;
    emergency?: boolean;
    isAvailableForRecognition?: boolean;
    aiSupported?: boolean;
  }): SignDefinition[] {
    let results = this.getAllSigns();

    if (params?.category && params.category !== 'ALL') {
      const cat = params.category.toUpperCase();
      results = results.filter(s => s.category.toUpperCase() === cat);
    }

    if (params?.difficulty && params.difficulty !== 'ALL') {
      const diff = params.difficulty.toUpperCase();
      results = results.filter(s => s.difficulty.toUpperCase() === diff);
    }

    if (params?.learningLevel && params.learningLevel > 0) {
      results = results.filter(s => s.learningLevel === params.learningLevel);
    }

    if (params?.handedness && params.handedness !== 'ALL') {
      const h = params.handedness.toUpperCase();
      results = results.filter(s => s.handedness.toUpperCase() === h);
    }

    if (params?.emergency !== undefined) {
      results = results.filter(s => s.emergency === params.emergency);
    }

    if (params?.isAvailableForRecognition !== undefined) {
      results = results.filter(s => (s.aiSupported || s.isAvailableForRecognition) === params.isAvailableForRecognition);
    }

    if (params?.aiSupported !== undefined) {
      results = results.filter(s => (s.aiSupported || s.isAvailableForRecognition) === params.aiSupported);
    }

    if (params?.query && params.query.trim().length > 0) {
      const q = params.query.toLowerCase().trim();
      results = results.filter(s =>
        (s.signId || '').toLowerCase().includes(q) ||
        s.id.toLowerCase().includes(q) ||
        s.canonicalName.toLowerCase().includes(q) ||
        s.displayName.toLowerCase().includes(q) ||
        s.englishMeaning.toLowerCase().includes(q) ||
        s.category.toLowerCase().includes(q) ||
        s.subcategory.toLowerCase().includes(q) ||
        s.aliases.some(a => a.toLowerCase().includes(q))
      );
    }

    return results;
  }

  public static getStatistics() {
    const all = this.getAllSigns();
    return {
      totalSigns: all.length,
      cameraRecognizable: all.filter(s => s.aiSupported || s.isAvailableForRecognition).length,
      beginner: all.filter(s => s.difficulty === 'EASY').length,
      intermediate: all.filter(s => s.difficulty === 'MEDIUM').length,
      advanced: all.filter(s => s.difficulty === 'HARD').length,
      emergency: all.filter(s => s.emergency).length,
      oneHanded: all.filter(s => s.handedness === 'ONE_HANDED').length,
      twoHanded: all.filter(s => s.handedness === 'TWO_HANDED').length,
      levels: {
        level1: all.filter(s => s.learningLevel === 1).length,
        level2: all.filter(s => s.learningLevel === 2).length,
        level3: all.filter(s => s.learningLevel === 3).length,
        level4: all.filter(s => s.learningLevel === 4).length
      }
    };
  }
}
